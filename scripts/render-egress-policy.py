#!/usr/bin/env python3
"""Render an optional nftables guard for a dedicated Wildbloom service UID.

Only render here: installing or applying the rules is an operator action.
"""

import argparse
import ipaddress
import json
from pathlib import Path


def address(value):
    if not isinstance(value, str) or "%" in value:
        raise ValueError("addresses must be bare IPv4 or IPv6 literals")
    return ipaddress.ip_address(value)


def render(config):
    if not isinstance(config, dict) or set(config) != {"uid", "allow_tcp", "dns_servers"}:
        raise ValueError("expected uid, allow_tcp and dns_servers only")
    uid = config["uid"]
    if type(uid) is not int or not 1 <= uid < 2**32 - 1:
        raise ValueError("uid must be a dedicated, non-root numeric UID")
    if not isinstance(config["allow_tcp"], list) or not isinstance(config["dns_servers"], list):
        raise ValueError("allow_tcp and dns_servers must be lists")
    exceptions = []
    for entry in config["allow_tcp"]:
        if not isinstance(entry, dict) or set(entry) != {"address", "port"}:
            raise ValueError("TCP exceptions need address and port only")
        ip = address(entry["address"])
        port = entry["port"]
        if type(port) is not int or not 1 <= port <= 65535:
            raise ValueError("TCP ports must be integers from 1 to 65535")
        family = "ip" if ip.version == 4 else "ip6"
        exceptions.append(f"        {family} daddr {ip} tcp dport {port} counter accept")
    for value in config["dns_servers"]:
        ip = address(value)
        family = "ip" if ip.version == 4 else "ip6"
        for protocol in ("udp", "tcp"):
            exceptions.append(f"        {family} daddr {ip} {protocol} dport 53 counter accept")
    return "\n".join([
        "# Generated by scripts/render-egress-policy.py; applies only to this dedicated UID.",
        "# The whole batch is atomic; other firewall tables are never flushed.",
        "add table inet wildbloom_egress",
        "flush table inet wildbloom_egress",
        "table inet wildbloom_egress {",
        "    chain output {",
        "        type filter hook output priority 10; policy accept;",
        f"        meta skuid {uid} jump daemon",
        "    }",
        "    chain daemon {",
        "        # Preserve responses to incoming connections, including the reverse proxy.",
        "        ct direction reply ct state { established, related } counter accept",
        *exceptions,
        "        # Also block this machine's public addresses, including future interface addresses.",
        "        fib daddr type local counter reject with icmpx type admin-prohibited",
        "        ip daddr { 0.0.0.0/8, 10.0.0.0/8, 100.64.0.0/10, 127.0.0.0/8, 169.254.0.0/16, 172.16.0.0/12, 192.0.0.0/24, 192.0.2.0/24, 192.88.99.0/24, 192.168.0.0/16, 198.18.0.0/15, 198.51.100.0/24, 203.0.113.0/24, 224.0.0.0/3 } counter reject with icmpx type admin-prohibited",
        "        meta nfproto ipv6 ip6 daddr != 2000::/3 counter reject with icmpx type admin-prohibited",
        "        ip6 daddr { 2001::/32, 2001:db8::/32, 2002::/16 } counter reject with icmpx type admin-prohibited",
        "        counter accept",
        "    }",
        "}",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, type=Path)
    args = parser.parse_args()
    try:
        policy = render(json.loads(args.config.read_text()))
    except (ValueError, OSError) as error:
        parser.error(str(error))
    print(policy, end="")


if __name__ == "__main__":
    main()
