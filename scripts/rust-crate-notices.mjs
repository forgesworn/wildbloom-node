// Generates desktop/src-tauri/THIRD_PARTY_RUST_NOTICES.md: every Rust crate
// compiled into the desktop app (all targets, normal dependencies) whose
// licence is not plain MIT or Apache-2.0, with the licence and notice files
// the crate ships.  Run after dependency changes:
//
//   node scripts/rust-crate-notices.mjs          (writes the file)
//   node scripts/rust-crate-notices.mjs --check  (fails if it is stale)
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = join(repo, 'desktop/src-tauri/Cargo.toml');
const output = join(repo, 'desktop/src-tauri/THIRD_PARTY_RUST_NOTICES.md');
const run = (args) => execFileSync('cargo', args, { cwd: repo, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 });

// MIT, Apache-2.0 and their OR-combinations need no entry here; anything else
// (other licences, or an AND with another licence) is listed.
// Old crates write "MIT/Apache-2.0" for "MIT OR Apache-2.0".
const permissiveOnly = (licence) => licence
  .replace(/\s*\/\s*/g, ' OR ')
  .replace(/[()]/g, ' ')
  .split(/\s+OR\s+/)
  .some((alternative) => /^\s*(MIT|Apache-2\.0|Apache-2\.0 WITH LLVM-exception)\s*$/.test(alternative))
  && !/\bAND\b/.test(licence);

// Crates that ship no licence file but share their repository and copyright
// holder with a listed crate that does.
const SIBLINGS = { 'alloc-stdlib': 'alloc-no-stdlib' };

const tree = run(['tree', '--locked', '--manifest-path', manifest, '-e', 'normal', '--target', 'all', '--prefix', 'none', '--format', '{p}|{l}']);
const wanted = new Map();
for (const line of tree.split('\n')) {
  const match = /^(\S+) v(\S+)[^|]*\|(.*)$/.exec(line.trim());
  if (!match) continue;
  const [, name, version] = match;
  // cargo tree marks repeated entries with a trailing "(*)".
  const licence = match[3].replace(/\s*\(\*\)\s*$/, '').trim();
  if (name.startsWith('wildbloom') || !licence || permissiveOnly(licence)) continue;
  wanted.set(`${name}@${version}`, { name, version, licence });
}

const metadata = JSON.parse(run(['metadata', '--locked', '--format-version', '1', '--manifest-path', manifest]));
const sections = [];
for (const key of [...wanted.keys()].sort()) {
  const { name, version, licence } = wanted.get(key);
  const pkg = metadata.packages.find((p) => p.name === name && p.version === version);
  const dir = pkg ? dirname(pkg.manifest_path) : null;
  const files = dir && existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile() && /^(licen[cs]e|copying|notice)/i.test(entry.name))
      .map((entry) => entry.name)
      .sort()
    : [];
  const parts = [`## ${name} ${version}`, '', `Licence: ${licence}`];
  if (pkg?.repository) parts.push(`Source: ${pkg.repository}`);
  parts.push('');
  if (files.length === 0) {
    const ids = [...new Set(licence.match(/[A-Za-z0-9.-]+/g).filter((id) => !['AND', 'OR', 'WITH'].includes(id)))];
    parts.push(
      'The crate ships no licence file. Its licence is the SPDX expression above; the texts are at',
      ...ids.map((id) => `<https://spdx.org/licenses/${id}.html>`),
      '',
    );
    const sibling = SIBLINGS[name];
    if (sibling) parts.push(`It is published from the same repository and copyright as ${sibling}, whose licence file appears under that crate.`, '');
  }
  for (const file of files) {
    const text = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    parts.push(`### ${file}`, '', '```text', text, '```', '');
  }
  sections.push(parts.join('\n'));
}

const body = `# Third-party Rust crate notices

Generated by \`node scripts/rust-crate-notices.mjs\`; do not edit by hand.

These Rust crates are compiled into the Wildbloom Node desktop app under
licences other than plain MIT or Apache-2.0 (or under such a licence combined
with another).  Their licence and notice files are reproduced below as
shipped.  Crates under MIT or Apache-2.0 alone are not listed.

${sections.join('\n')}`;

if (process.argv.includes('--check')) {
  const current = existsSync(output) ? readFileSync(output, 'utf8') : '';
  if (current !== body) {
    process.stderr.write('THIRD_PARTY_RUST_NOTICES.md is stale; run node scripts/rust-crate-notices.mjs\n');
    process.exit(1);
  }
  process.stdout.write(`Rust crate notices are current (${wanted.size} crates).\n`);
} else {
  writeFileSync(output, body);
  process.stdout.write(`Wrote ${wanted.size} crate notices.\n`);
}
